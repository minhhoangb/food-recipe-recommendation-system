"""Error analysis on the validation split: error patterns with numbers, cases, train-validation gap.

    python -m src.error_analysis --config configs/default.yaml \
        --system E01=models/tfidf-main-1f1f4ce5 --system E03=models/bm25-main-1f1f4ce5 \
        --system LSA=models/lsa-main-1f1f4ce5 --system E04=models/minilm_pretrained-E04-main-1f1f4ce5 \
        --system E05=models/minilm_pretrained-E05-main-1f1f4ce5 \
        --system FT=models/minilm_finetuned-E04-main-1f1f4ce5 --encoder FT=models/minilm_finetuned-main-cpu1ep

Rewrites everything below the GENERATED marker of reports/error_analysis.md (the written findings
above it are kept) and writes reports/error_analysis_queries.csv (one row per query). MRR@10 uses
the single-origin definition of ranx, so the "all" rows equal the validation MRR@10 of
reports/comparison.csv for the same bundles.
"""

from __future__ import annotations

import argparse
import random
import sys
from collections import Counter

import pandas as pd

from src.config import load_config, processed_dir
from src.evaluate import load_split, load_system
from src.normalize import normalize_ingredients
from src.utils import REPO_ROOT, read_json, read_jsonl

TOP_K = 10
COMMON_SHARE = 0.02  # same threshold as query generation (configs: queries.common_df_threshold)
RARE_DF = 5
MARKER = "<!-- GENERATED by python -m src.error_analysis; edit above this line only -->"
# (title, column, {value: label}) for the per-pattern MRR@10 tables
BUCKETS = [
    ("Query length (ingredients)", "n_ingredients", {n: str(n) for n in range(1, 7)}),
    (
        "Share of common ingredients in the query (train df > 2%)",
        "common",
        {"none": "none", "some": "1-50%", "most": "> 50%"},
    ),
    (
        "Rarest query ingredient (document frequency in train)",
        "rarity",
        {"unseen": "unseen in train", "rare": f"1-{RARE_DF}", "seen": f"> {RARE_DF}"},
    ),
    (
        "Query has an ingredient whose singular/plural twin is a separate vocabulary entry",
        "plural_twin",
        {True: "yes", False: "no"},
    ),
    (
        "Size of the origin recipe (normalised ingredients)",
        "origin_size",
        {"small": "<= 6", "medium": "7-10", "large": "> 10"},
    ),
]


def origin_rank(ranked: list[str], origins: list[str]) -> int | None:
    """1-based rank of the first origin recipe in the top list, None when it is missing."""
    return next((rank for rank, rid in enumerate(ranked, 1) if rid in origins), None)


def twin(name: str, vocabulary: set[str]) -> str | None:
    """A singular/plural spelling of `name` that is also a separate vocabulary entry."""
    candidates = [name + "s", name + "es", name[:-1] if name.endswith("s") else ""]
    return next((c for c in candidates if c and c in vocabulary), None)


def query_features(ingredients: list[str], df: Counter, n_train: int, origin_len: int) -> dict:
    """Pattern columns for one normalised query (never empty for synthetic queries)."""
    common = sum(df[i] > COMMON_SHARE * n_train for i in ingredients) / len(ingredients)
    rarest = min(df[i] for i in ingredients)
    return {
        "n_ingredients": len(ingredients),
        "common": "none" if common == 0 else ("some" if common <= 0.5 else "most"),
        "min_df": rarest,
        "rarity": "unseen" if rarest == 0 else ("rare" if rarest <= RARE_DF else "seen"),
        "plural_twin": any(twin(i, set(df)) for i in ingredients),
        "origin_size": "small" if origin_len <= 6 else ("medium" if origin_len <= 10 else "large"),
    }


def mrr(ranks: pd.Series) -> float:
    return float(ranks.map(lambda r: 0.0 if pd.isna(r) else 1.0 / r).mean())


def markdown_table(header: list[str], rows: list[list]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    return lines + ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows] + [""]


def bucket_rows(frame: pd.DataFrame, systems: list[str], column: str, labels: dict) -> list[list]:
    parts = [(label, frame[frame[column] == value]) for value, label in labels.items()] + [("**all**", frame)]
    return [
        [label, len(part)] + [f"{mrr(part[f'rank_{s}']):.3f}" for s in systems]
        for label, part in parts
        if len(part)
    ]


def pick_cases(
    frame: pd.DataFrame, systems: list[str], seed: int, per_group: int = 7
) -> list[tuple[str, str]]:
    """(group, query_id) pairs: deterministic samples of four contrasting situations."""
    lexical, dense = "E03", "FT" if "FT" in systems else "E04"
    hit = pd.concat({s: frame[f"rank_{s}"].notna() for s in systems}, axis=1)
    groups = {
        "every system misses the origin": ~hit.any(axis=1),
        f"{lexical} finds it at rank 1, {dense} misses the top 10": (frame[f"rank_{lexical}"] == 1)
        & ~hit[dense],
        f"{dense} finds it, {lexical} misses the top 10": hit[dense] & ~hit[lexical],
        f"rare ingredient (train df <= {RARE_DF})": frame["min_df"] <= RARE_DF,
    }
    rng, cases, used = random.Random(seed), [], set()
    for name, mask in groups.items():
        candidates = sorted(set(frame.loc[mask, "query_id"]) - used)
        chosen = sorted(rng.sample(candidates, min(per_group, len(candidates))))
        used.update(chosen)
        cases += [(name, query_id) for query_id in chosen]
    return cases


def case_block(group: str, query: dict, row: pd.Series, tops: dict, corpus: dict) -> list[str]:
    origins = query["origin_recipe_ids"]
    origin_text = ", ".join(
        f"`{o}` *{corpus[o]['title']}* ({len(corpus[o]['ingredients_normalized'])} ingredients)"
        for o in origins
    )
    lines = [
        f"#### {query['query_id']} ({group})",
        "",
        f"Query: `{'; '.join(query['ingredients'])}` (rarest train df {row['min_df']})<br>",
        f"Origin: {origin_text}",
        "",
    ]
    for system, ranked in tops.items():
        rank = row[f"rank_{system}"]
        hits = [
            (f"**{rid}**" if rid in origins else f"`{rid}`") + f" {corpus[rid]['title'][:28]!r}"
            for rid in ranked[:5]
        ]
        shown = "-" if pd.isna(rank) else int(rank)
        lines.append(f"- {system} (origin rank {shown}): {', '.join(hits) or 'no result'}")
    return lines + [""]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--config", default="configs/default.yaml")
    parser.add_argument("--system", action="append", required=True, help="LABEL=models/<run_id>")
    parser.add_argument("--encoder", action="append", default=[], help="LABEL=<checkpoint> (fine-tuned)")
    parser.add_argument("--out", default="reports/error_analysis.md")
    args = parser.parse_args(argv)

    cfg = load_config(args.config)
    directory = processed_dir(cfg)
    corpus = {r["recipe_id"]: r for r in read_jsonl(directory / "corpus.jsonl")}
    train_ids = set(read_json(directory / "splits.json")["train"])
    df = Counter(
        i for rid in train_ids for i in set(normalize_ingredients(corpus[rid]["ingredients_normalized"]))
    )
    queries, _ = load_split(directory, "validation")

    encoders = dict(spec.split("=", 1) for spec in args.encoder)
    tops: dict[str, dict[str, list[str]]] = {}
    for spec in args.system:
        label, path = spec.split("=", 1)
        retriever = load_system(REPO_ROOT / path, encoders.get(label))[0]
        tops[label] = {
            q["query_id"]: [h.recipe_id for h in retriever.search(q["ingredients"], TOP_K)] for q in queries
        }
        print(f"{label}: searched {len(queries)} validation queries")
    systems = list(tops)

    rows = []
    for q in queries:
        wanted = normalize_ingredients(q["ingredients"])
        origin_len = len(corpus[q["origin_recipe_ids"][0]]["ingredients_normalized"])
        row = {"query_id": q["query_id"], **query_features(wanted, df, len(train_ids), origin_len)}
        for s in systems:
            ranked = tops[s][q["query_id"]]
            row[f"rank_{s}"] = origin_rank(ranked, q["origin_recipe_ids"])
            top1 = normalize_ingredients(corpus[ranked[0]]["ingredients_normalized"]) if ranked else []
            row[f"top1_covers_{s}"] = row[f"rank_{s}"] != 1 and bool(ranked) and set(wanted) <= set(top1)
        rows.append(row)
    frame = pd.DataFrame(rows)

    lines = [MARKER, "", f"## Tables (validation, {len(frame)} queries, MRR@10 per system)", ""]
    for title, column, labels in BUCKETS:
        lines += [f"### {title}", ""] + markdown_table(
            ["", "queries", *systems], bucket_rows(frame, systems, column, labels)
        )
    lines += [
        "### Proxy-label misses: rank-1 recipe is not the origin but contains every query ingredient",
        "",
    ]
    lines += markdown_table(
        ["", *systems], [["queries", *(int(frame[f"top1_covers_{s}"].sum()) for s in systems)]]
    )

    comparison = REPO_ROOT / "reports" / "comparison.csv"
    if comparison.exists():
        table = pd.read_csv(comparison)
        cv = table["cv_mrr@10_mean"].map(lambda v: "-" if pd.isna(v) else f"{v:.3f}")
        gap = table["train_mrr@10"] - table["val_mrr@10"]
        gap_rows = [
            [r["experiment"], f"{r['train_mrr@10']:.3f}", cv[i], f"{r['val_mrr@10']:.3f}", f"{gap[i]:+.3f}"]
            for i, r in table.iterrows()
        ]
        lines += ["## Train-validation gap (MRR@10, from reports/comparison.csv)", ""]
        lines += markdown_table(["System", "Train proxy", "CV", "Validation", "Train - validation"], gap_rows)

    by_id, indexed = {q["query_id"]: q for q in queries}, frame.set_index("query_id")
    cases = pick_cases(frame, systems, cfg.seed)
    lines += [f"## Cases ({len(cases)} validation queries, top 5 per system, origin recipe in bold)", ""]
    for group, query_id in cases:
        ranked = {system: tops[system][query_id] for system in systems}
        lines += case_block(group, by_id[query_id], indexed.loc[query_id], ranked, corpus)

    out = REPO_ROOT / args.out
    head = out.read_text(encoding="utf-8").split(MARKER)[0] if out.exists() else "# Error analysis\n\n"
    out.write_text(head + "\n".join(lines), encoding="utf-8")
    frame.to_csv(out.with_name("error_analysis_queries.csv"), index=False)
    print(f"{len(cases)} cases -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
